"""Export an Int8Model as $readmemh hex files for the FPGA, and load it back.

Every .hex file holds one two's complement word per line (2 hex digits for
8-bit words, 8 for 32-bit), in the address order given by its "layout" in
model.json. params.vh carries the matching Verilog constants.
"""

import json
from dataclasses import asdict
from pathlib import Path

import numpy as np

from . import vocab
from .int8_model import Int8Model
from .net import ModelConfig

FORMAT_VERSION = 1

# name -> (file, word bits, signed, address layout)
TENSORS = {
    "emb": ("embedding.hex", 8, True, "addr = token * EMB_DIM + d"),
    "w1": ("fc1_weight.hex", 8, True, "addr = out * IN_DIM + (position * EMB_DIM + d); position 0 = oldest char"),
    "b1": ("fc1_bias.hex", 32, True, "addr = out"),
    "w2": ("fc2_weight.hex", 8, True, "addr = out_token * HIDDEN + j"),
    "b2": ("fc2_bias.hex", 32, True, "addr = out_token"),
    "act_lut": ("tanh_lut.hex", 8, True, "addr = pre-activation int8 as unsigned byte (two's complement)"),
}
TEST_VECTORS = {
    "context": ("test_context.hex", 8, False, "addr = vector * CONTEXT + position (token ids)"),
    "hidden": ("test_hidden.hex", 8, True, "addr = vector * HIDDEN + j"),
    "logits": ("test_logits.hex", 32, True, "addr = vector * VOCAB_SIZE + token (fc2 accumulators)"),
    "argmax": ("test_argmax.hex", 8, False, "addr = vector (predicted next token)"),
}


def write_hex(path: Path, values: np.ndarray, bits: int):
    mask, digits = (1 << bits) - 1, bits // 4
    path.write_text("".join(f"{int(v) & mask:0{digits}x}\n" for v in np.asarray(values).ravel()))


def read_hex(path: Path, bits: int, signed: bool = True) -> np.ndarray:
    vals = np.array([int(line, 16) for line in Path(path).read_text().split()], dtype=np.int64)
    if signed:
        vals = np.where(vals >= 1 << (bits - 1), vals - (1 << bits), vals)
    return vals


def _verilog_params(q: Int8Model, acc_bits: dict[str, int], test_count: int) -> str:
    cfg = q.config
    mult_bits = q.scales["mult_bits"]
    lines = [
        "// Auto-generated by model/export.py -- do not edit.",
        "// CharMLP: CONTEXT tokens -> embedding -> fc1 -> activation -> fc2 -> logits",
        f"localparam VOCAB_SIZE = {cfg.vocab_size};",
        f"localparam TOKEN_BITS = {(cfg.vocab_size - 1).bit_length()};",
        f"localparam CONTEXT    = {cfg.context};",
        f"localparam EMB_DIM    = {cfg.emb_dim};",
        f"localparam IN_DIM     = {cfg.in_dim};",
        f"localparam HIDDEN     = {cfg.hidden};",
        "",
        "// 1: hidden = tanh_lut[pre-activation byte], 0: hidden = relu (clamp to [0, 127])",
        f"localparam ACT_TANH   = {int(cfg.activation == 'tanh')};",
        "",
        "// fc1 accumulator -> int8: (acc1 * REQ1_MULT + (1 << (REQ1_SHIFT - 1))) >>> REQ1_SHIFT, then saturate",
        f"localparam REQ1_MULT_BITS = {mult_bits};",
        f"localparam [{mult_bits - 1}:0] REQ1_MULT = {mult_bits}'d{q.req1_mult};",
        f"localparam REQ1_SHIFT = {q.req1_shift};",
        "",
        "// Worst-case signed widths over all possible inputs",
        f"localparam ACC1_BITS  = {acc_bits['acc1']};",
        f"localparam REQ1_PRODUCT_BITS = {acc_bits['req1_product']};",
        f"localparam ACC2_BITS  = {acc_bits['acc2']};",
        "",
        f"localparam TOKEN_NEWLINE = {vocab.NEWLINE};",
        f"localparam TOKEN_SPACE   = {vocab.SPACE};",
        f"localparam TEST_VECTORS  = {test_count};",
        "",
    ]
    return "\n".join(lines)


def export(
    q: Int8Model,
    out_dir: str | Path,
    test_contexts: np.ndarray,
    metrics: dict | None = None,
    hparams: dict | None = None,
) -> dict:
    """Write hex weights, LUTs, vocab tables, test vectors, params.vh and model.json."""
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    cfg = q.config
    files = {}

    def emit(name, spec, values, shape):
        fname, bits, signed, layout = spec
        write_hex(out / fname, values, bits)
        files[name] = {"file": fname, "bits": bits, "signed": signed, "shape": list(shape), "layout": layout}

    for name, spec in TENSORS.items():
        arr = getattr(q, name)
        if arr is not None:
            emit(name, spec, arr, arr.shape)

    emit("token_to_ascii", ("token_to_ascii.hex", 8, False, "addr = token"),
         [ord(c) for c in vocab.CHARS], (cfg.vocab_size,))  # fmt: skip
    emit("ascii_to_token", ("ascii_to_token.hex", 8, False, "addr = 7-bit ASCII code; unknown -> space"),
         vocab.ascii_to_token_table(), (128,))  # fmt: skip

    ctx = np.asarray(test_contexts, dtype=np.int64)
    logits = q.int_logits(ctx)
    for name, values in (("context", ctx), ("hidden", q.hidden(ctx)), ("logits", logits), ("argmax", logits.argmax(1))):
        emit(f"test_{name}", TEST_VECTORS[name], values, values.shape)

    acc_bits = q.accumulator_bits()
    (out / "params.vh").write_text(_verilog_params(q, acc_bits, len(ctx)))

    manifest = {
        "format_version": FORMAT_VERSION,
        "config": asdict(cfg),
        "vocab": vocab.CHARS,
        "quant": {
            "scheme": "symmetric per-tensor int8, zero-point 0; int32 biases at accumulator scale",
            "req1_mult": q.req1_mult,
            "req1_shift": q.req1_shift,
            "scales": q.scales,
            "accumulator_bits": acc_bits,
        },
        "files": files,
        "num_weights": int(sum(getattr(q, n).size for n in ("emb", "w1", "b1", "w2", "b2"))),
        "metrics": metrics or {},
        "hparams": hparams or {},
    }
    (out / "model.json").write_text(json.dumps(manifest, indent=2) + "\n")
    return manifest


def load(out_dir: str | Path) -> Int8Model:
    """Rebuild the Int8Model purely from the exported files (what the FPGA sees)."""
    out = Path(out_dir)
    manifest = json.loads((out / "model.json").read_text())
    if manifest["format_version"] != FORMAT_VERSION:
        raise ValueError(f"unsupported model.json format {manifest['format_version']}")
    files = manifest["files"]
    dtypes = {8: np.int8, 32: np.int32}

    def tensor(name):
        if name not in files:
            return None
        f = files[name]
        return read_hex(out / f["file"], f["bits"], f["signed"]).astype(dtypes[f["bits"]]).reshape(f["shape"])

    return Int8Model(
        config=ModelConfig(**manifest["config"]),
        emb=tensor("emb"),
        w1=tensor("w1"),
        b1=tensor("b1"),
        w2=tensor("w2"),
        b2=tensor("b2"),
        req1_mult=manifest["quant"]["req1_mult"],
        req1_shift=manifest["quant"]["req1_shift"],
        act_lut=tensor("act_lut"),
        scales=manifest["quant"]["scales"],
    )


def load_test_vectors(out_dir: str | Path) -> dict[str, np.ndarray]:
    out = Path(out_dir)
    files = json.loads((out / "model.json").read_text())["files"]
    return {
        name: read_hex(out / files[f"test_{name}"]["file"], bits, signed).reshape(files[f"test_{name}"]["shape"])
        for name, (_, bits, signed, _) in TEST_VECTORS.items()
    }
